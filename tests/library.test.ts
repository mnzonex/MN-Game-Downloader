import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { getDb, dbSetSetting } from '../src/engine/db';
import { libraryList, scanLibrary, recordCompletion, historyList, setExecutable, rememberGame, importLibraryCandidates, removeLibraryGame, addManualLibraryGame, manualLibraryList, setManualGameCover, removeManualLibraryGame } from '../src/engine/Library';
import Database from 'better-sqlite3';
async function run() {
  const root = path.resolve('.test-data', 'library-' + Date.now());
  process.env.MN_DATA_DIR = path.join(root, 'db');
  fs.mkdirSync(process.env.MN_DATA_DIR, { recursive: true });
  const legacy = new Database(path.join(process.env.MN_DATA_DIR, 'mn-engine.db'));
  legacy.exec(`CREATE TABLE settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
    INSERT INTO settings VALUES ('upgrade_preservation','keep');
    CREATE TABLE torrents (id TEXT PRIMARY KEY, name TEXT, magnet TEXT, save_path TEXT, dest_path TEXT,
      status TEXT, error_msg TEXT, progress REAL, size INTEGER, speed_dl INTEGER, speed_ul INTEGER,
      peers INTEGER, seeds INTEGER, eta_secs INTEGER, added_at INTEGER, completed_at INTEGER, hidden INTEGER);
    INSERT INTO torrents (id,name,status,hidden) VALUES ('existing','Existing download','downloading',0);`);
  legacy.close();
  const library = path.join(root, 'games'); const game = path.join(library, 'Game');
  fs.mkdirSync(game, { recursive: true });
  const id = 'a'.repeat(40);
  const manifest = path.join(game, '.mn-game.json');
  fs.writeFileSync(manifest, JSON.stringify({ schema: 1, infohash: id, name: 'Test Game', files: [], total_size: 3, verified_at: new Date().toISOString() }));
  fs.writeFileSync(path.join(game, 'setup.exe'), 'fixture');
  fs.writeFileSync(path.join(game, 'play.exe'), 'fixture');
  dbSetSetting('download_path', library);
  const preview = await scanLibrary(library);
  assert.equal(libraryList().length, 0, 'scan never silently imports');
  assert.equal(preview.candidates.length, 1);
  await importLibraryCandidates(preview.candidates.map(c => c.token));
  assert.equal(libraryList().length, 1);
  assert.throws(() => setExecutable(id, path.join(game, 'setup.exe')), /installer/);
  assert.throws(() => setExecutable(undefined, path.join(game, 'play.exe')), /Select a downloaded game/);
  removeLibraryGame(id); assert.equal(libraryList().length, 0);
  assert.ok(fs.existsSync(manifest), 'remove preserves files');
  await scanLibrary(); assert.equal(libraryList().length, 0, 'refresh cannot reimport removed entries');
  const again = await scanLibrary(library); await importLibraryCandidates(again.candidates.map(c => c.token));
  const fixtures = path.join(library, '.test-data', 'fixture'); fs.mkdirSync(fixtures, { recursive: true });
  fs.writeFileSync(path.join(fixtures, '.mn-game.json'), fs.readFileSync(manifest));
  assert.equal((await scanLibrary(library)).candidates.length, 1, 'developer fixtures excluded');
  setExecutable(id, path.join(game, 'play.exe'));
  const manualExe = path.join(root, 'manual-game.exe');
  fs.writeFileSync(manualExe, 'fixture, never executed');
  const manual = addManualLibraryGame('My Manual Game', manualExe);
  assert.equal(manual.name, 'My Manual Game');
  assert.equal(manual.launcherPath, manualExe);
  assert.equal(manualLibraryList().length, 1);
  assert.equal(addManualLibraryGame('Renamed Manual Game', manualExe).id, manual.id, 'adding the same launcher must update rather than duplicate');
  assert.equal(manualLibraryList()[0].name, 'Renamed Manual Game');
  const setupExe = path.join(root, 'setup-2.EXE'); fs.writeFileSync(setupExe, 'installer fixture');
  assert.throws(() => addManualLibraryGame('Installer', setupExe), /installer/);
  const manualCover = path.join(root, 'manual-cover.png');
  fs.writeFileSync(manualCover, Buffer.from([137, 80, 78, 71, 13, 10, 26, 10, 0, 0, 0, 0]));
  assert.equal(setManualGameCover(manual.id, manualCover).coverPath, manualCover);
  assert.equal(manualLibraryList()[0].coverPath, manualCover);
  const shortcut = path.join(root, 'manual-game.lnk');
  fs.writeFileSync(shortcut, 'shortcut fixture');
  const manualShortcut = addManualLibraryGame('Shortcut Game', shortcut);
  assert.equal(manualShortcut.launcherPath, shortcut);
  assert.equal(manualLibraryList().length, 2);
  assert.equal(removeManualLibraryGame(manual.id), true, 'remove deletes only the manual Library record');
  assert.equal(manualLibraryList().length, 1, 'other manually added games stay in the Library');
  assert.equal(manualLibraryList()[0].id, manualShortcut.id);
  assert.equal(removeManualLibraryGame(manual.id), false, 'removing the same entry twice is harmless');
  assert.ok(fs.existsSync(manualExe), 'remove from Library must preserve the game executable');
  assert.ok(fs.existsSync(shortcut), 'remove from Library must preserve the desktop shortcut');
  assert.ok(fs.existsSync(manualCover), 'remove from Library must preserve the uploaded cover file');
  const moved = path.join(library, 'Moved Game'); fs.renameSync(game, moved);
  const movedScan = await scanLibrary(library); await importLibraryCandidates(movedScan.candidates.map(c => c.token)); assert.equal(libraryList()[0].folder, moved);
  assert.equal(libraryList()[0].executable, path.join(moved, 'play.exe'));
  await rememberGame(id, 'Display title');
  const row = { id, name: 'Test Game', size: 3, dest_path: library, magnet: 'magnet:?xt=urn:btih:' + id, added_at: 1 };
  await recordCompletion(row, path.join(moved, '.mn-game.json'));
  await recordCompletion(row, path.join(moved, '.mn-game.json'));
  assert.equal(historyList().length, 1, 'completion is idempotent');
  await recordCompletion({ ...row, added_at: 2 }, path.join(moved, '.mn-game.json'));
  assert.equal(historyList().length, 2, 'repeat download has separate history');
  assert.equal(historyList()[0].name, 'Display title');
  await recordCompletion({ ...row, added_at: 3, task_kind: 'repair' }, path.join(moved, '.mn-game.json'));
  assert.equal(historyList()[0].taskKind, 'repair');
  assert.ok((getDb().prepare('PRAGMA table_info(torrents)').all() as any[]).some(c => c.name === 'task_kind')); 
  const db = getDb();
  assert.equal((db.prepare("SELECT value FROM settings WHERE key='upgrade_preservation'").get() as any).value, 'keep');
  assert.equal((db.prepare("SELECT status FROM torrents WHERE id='existing'").get() as any).status, 'downloading', 'startup must not falsely pause active downloads');
  console.log('Library tests passed: import, moved folder, executable relocation, history dedup/repeat, existing data retained.');
  db.close();
}
run().catch(error => { console.error(error); process.exitCode = 1; });